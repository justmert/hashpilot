/**
 * Hardhat Configuration Generator
 * Generates Hardhat 3 config files, sample sources and .env templates for
 * Hedera networks. Everything is ESM, as Hardhat 3 requires.
 */

/**
 * Network configuration
 */
export interface NetworkConfig {
  name: string;
  rpcUrl: string;
  chainId: number;
  accounts?: string[];
}

